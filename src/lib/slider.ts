/**
 * Циклэн эргэдэг слайдерын байрлалын математик.
 *
 * Нэг зурвасыг `-active × 100%`-аар шилжүүлэх энгийн арга нь сүүлийн
 * слайдаас эхнийх рүү эргэхэд БҮХ слайдаар ухарч буцдаг. Оронд нь слайд
 * бүрийг идэвхтэйгээсээ ХАМГИЙН ДӨТ талд байрлуулбал цикл эргэлт ч
 * зөвхөн нэг дэлгэцийн зайд, зөв чиглэлд болно.
 */

/**
 * Слайд `i` нь идэвхтэй `base`-ээс хэдэн байрын зайд байхыг циклээр буцаана.
 * Утга нь ойролцоогоор [−n/2, n/2] мужид байна.
 *
 * Тэгш тоотой үед яг эсрэг талын слайд (off = n/2) нь БАРУУН талд үлдэнэ —
 * аль ч тал ижил зайтай тул сонголт дурын, гол нь тогтвортой байх явдал.
 */
export function cyclicOffset(i: number, base: number, total: number): number {
  if (total <= 0) return 0;
  let off = ((i - base) % total + total) % total; // 0 … total-1
  if (off > total / 2) off -= total;
  return off;
}

/**
 * Слайд циклийн "цаад талаар" үсэрсэн эсэх.
 *
 * Ийм слайд нь дэлгэцийн нэг захаас нөгөө рүү шууд шилжих ёстой (харагдахгүй
 * газраа) — эс тэгвээс бүх дэлгэцийг хөндлөн гарч өнгөрнө. Дуудагч тал нь
 * үүнд `transition: none` өгнө.
 */
export function slideJumped(i: number, from: number, to: number, total: number): boolean {
  return Math.abs(cyclicOffset(i, to, total) - cyclicOffset(i, from, total)) > 1;
}
