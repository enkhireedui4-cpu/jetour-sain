/**
 * 360° эргэлтийн цэвэр тооцоо.
 *
 * Компонент дотор биш, энд байгаа шалтгаан: эдгээр нь чирэлтийн зөв байдлыг
 * тодорхойлдог ГОЛ логик боловч DOM шаарддаггүй. Тусад нь байвал тестлэж
 * болно — эргэлт "гацах", "үсрэх", "буруу тийш эргэх" зэрэг алдааг
 * гараар оролдохгүйгээр барина.
 */

/**
 * Индексийг тойрог болгож хязгаарлана (сөрөг утгыг ч зөв боловсруулна).
 *
 * JS-ийн `%` нь сөрөг тоонд сөрөг үлдэгдэл өгдөг (`-1 % 36 === -1`) тул
 * шууд ашиглавал эхний кадраас ухрахад массивын гадна гарч, зураг алга болно.
 */
export function wrapIndex(index: number, total: number): number {
  if (total <= 0) return 0;
  return ((index % total) + total) % total;
}

/**
 * Хуримтлагдсан чирэлтээс хэдэн кадр урагшлахыг тооцно.
 *
 * `Math.trunc` ашигласан нь санаатай: тэгийн зүг руу тайрдаг тул баруун,
 * зүүн хоёр тийш ижил мэдрэмжтэй болно (`Math.floor` бол зүүн тийш
 * нэг кадраар түрүүлж эхэлдэг).
 */
export function framesToAdvance(accumulatedPx: number, pxPerFrame: number): number {
  if (!Number.isFinite(pxPerFrame) || pxPerFrame <= 0) return 0;
  const n = Math.trunc(accumulatedPx / pxPerFrame);
  /* `Math.trunc(-0.6)` нь `-0` буцаадаг. Арифметикт `-0 === 0` тул алдаа
     үүсгэхгүй ч, дуудагч талд `Object.is(n, 0)` эсвэл тестэд гэнэтийн
     үр дүн өгдөг. Тэгийг ганц хэлбэрт оруулав. */
  return n === 0 ? 0 : n;
}

/**
 * Нэг кадр солигдоход шаардагдах чирэлтийн зай (px).
 *
 * Бүтэн эргэлт ≈ блокийн өргөний 0.55 дахин чирэлт, өөрөөр хэлбэл дэлгэцийн
 * хагасыг чирэхэд машин бүтэн эргэнэ. (Өмнө 1.1 байсан нь бүтэн дэлгэц
 * дамжуулж чирэх шаардлагатай болж, хэтэрхий мөлхөө мэдрэгддэг байв.)
 *
 * 6px нь доод хязгаар — үүнээс бага бол хуруу чичрэхэд л кадр үсэрнэ.
 */
export function pxPerFrameFor(containerWidth: number, total: number): number {
  if (total <= 0) return 16;
  return Math.max(6, (containerWidth * 0.55) / total);
}
